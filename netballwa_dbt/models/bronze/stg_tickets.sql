SELECT
    RECORD_ID AS TICKET_ID,
    DATA:sellerId::VARCHAR AS SELLER_ID,
    DATA:eventId::VARCHAR AS EVENT_ID,
    DATA:transactionId::VARCHAR AS TRANSACTION_ID,
    DATA:customerId::VARCHAR AS CUSTOMER_ID,
    DATA:ticketTypeId::VARCHAR AS TICKET_TYPE_ID,
    DATA:ticketName::VARCHAR AS TICKET_NAME,
    DATA:name::VARCHAR AS ATTENDEE_NAME,
    DATA:email::VARCHAR AS EMAIL,
    DATA:status::VARCHAR AS STATUS,
    DATA:seatingInfo AS SEATING_INFO,
    DATA:seatingInfo.sectionName::VARCHAR AS SEAT_SECTION,
    DATA:seatingInfo.rowName::VARCHAR AS SEAT_ROW,
    DATA:seatingInfo.seatName::VARCHAR AS SEAT_NAME,
    DATA:seatingInfo.gate::VARCHAR AS SEAT_GATE,
    TRY_TO_TIMESTAMP_TZ(DATA:createdAt::VARCHAR) AS CREATED_AT,
    SOURCE_UPDATED_AT AS UPDATED_AT,
    FIRST_LOADED_AT,
    LAST_CHANGED_AT,
    DATA:firstname::VARCHAR AS FIRST_NAME,
    DATA:lastname::VARCHAR AS LAST_NAME,
    DATA:cartItemId::VARCHAR AS CART_ITEM_ID,
    DATA:categoryRef::VARCHAR AS CATEGORY_REF,
    DATA:categoryName::VARCHAR AS CATEGORY_NAME,
    DATA:barcode::VARCHAR AS BARCODE,
    DATA:type::VARCHAR AS TICKET_TYPE,
    DATA:subscriptionId::VARCHAR AS SUBSCRIPTION_ID,
    DATA:checkoutId::VARCHAR AS CHECKOUT_ID,
    DATA:checkoutItemId::VARCHAR AS CHECKOUT_ITEM_ID,
    DATA:purchaseIntentId::VARCHAR AS PURCHASE_INTENT_ID,
    DATA:salesChannelId::VARCHAR AS SALES_CHANNEL_ID,
    DATA:underShopId::VARCHAR AS UNDER_SHOP_ID,
    DATA:origin::VARCHAR AS ORIGIN,
    DATA:currency::VARCHAR AS CURRENCY,
    TRY_TO_DECIMAL(DATA:realPrice::VARCHAR, 18, 4) AS REAL_PRICE,
    TRY_TO_DECIMAL(DATA:regularPrice::VARCHAR, 18, 4) AS REGULAR_PRICE,
    TRY_TO_BOOLEAN(DATA:expired::VARCHAR) AS IS_EXPIRED,
    TRY_TO_BOOLEAN(DATA:personalized::VARCHAR) AS IS_PERSONALISED,
    DATA:street::VARCHAR AS LOCATION_STREET,
    DATA:city::VARCHAR AS LOCATION_CITY,
    DATA:state::VARCHAR AS LOCATION_STATE,
    DATA:postal::VARCHAR AS LOCATION_POSTAL,
    DATA:country::VARCHAR AS LOCATION_COUNTRY,
    TRY_TO_DATE(DATA:extraFields.birth_date::VARCHAR) AS DOB,
    NULLIF(TRIM(DATA:extraFields.gender::VARCHAR), '') AS GENDER,
    DATA:extraFields.member_number::VARCHAR AS MEMBER_NUMBER,
    DATA:extraFields.member_since::VARCHAR AS MEMBER_SINCE,
    TRY_TO_DATE(DATA:extraFields.member_since::VARCHAR) AS MEMBER_SINCE_DATE,
    DATA:extraFields AS EXTRA_FIELDS,
    DATA:personalizations AS PERSONALISATIONS,
    DATA:entryPermissions AS ENTRY_PERMISSIONS,
    DATA:excludedEventIds AS EXCLUDED_EVENT_IDS,
    SOURCE_CONTEXT AS SOURCE_CONTEXT
FROM {{ source('vivenu_native', 'vivenu_raw_current') }}
WHERE STREAM_NAME = 'tickets'