 p.PAYLOAD AS PUBLISHED_PAYLOAD,s.PAYLOAD AS CURRENT_PAYLOAD
FROM V_EVENT_CANDIDATES s JOIN V_PUBLISHED_EVENTS p
 ON p.TARGET_NAME=s.TARGET_NAME AND p.EXTERNAL_ID=s.EXTERNAL_ID
 AND p.PAYLOAD:properties.order_id::VARCHAR=s.PAYLOAD:properties.order_id::VARCHAR
WHERE p.PAYLOAD IS DISTINCT FROM PARSE_JSON(TO_JSON(s.PAYLOAD));

