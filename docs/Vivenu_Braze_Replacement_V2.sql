/*
VIVENU TO BRAZE V2 - USES THE UPDATED VIEWS
Prerequisite: run Vivenu_Braze_View_Updates.sql first.
Source views: RAW_INGESTION.VIVENU_NATIVE.CUSTOMERS, TRANSACTIONS, TICKETS, EVENTS.
Build schema: BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.
Targets: the four existing BRAZE_CLOUD_PRODUCTION.INGESTION.TICKETEK_* tables.

Run sections 1-6 for installation and a validation build. Section 7 has commented
cutover commands. On first installation the new task is suspended. Re-running
this script does not suspend an already enabled task: suspend it before upgrades.
No changes to source views, old tasks or existing Braze targets during validation.

CONFIRMED RULES
- Vivenu contains new purchases. Keep historical Ticketek target rows.
- Netball WA treats purchase as marketing consent. Eligible profile payloads set
  email_subscribe='subscribed' without requiring MARKETING_CONSENT=true.
- Preserve legacy age rules through configuration: match profile groups have no
  age threshold; member profile and membership event groups require age 18.
  NULL DOB does not meet an age threshold. Global email_subscribe remains subscribed.
- Preserve legacy email identity SHA2(TRIM(email),256), including source case.
- Preserve the four output contracts and event names. Prefix new order IDs vivenu:.

CONFIGURATION
- No fixed event IDs or years. V_EVENT_MAP derives rows from EVENTS.
- Default rule: event names containing 'membership' classify as MEMBER; other
  named ticket events classify as MATCH. This is a naming convention inferred
  from the supplied membership examples, not a verified Vivenu type enumeration.
  Plan/MULTI evidence conflicting with default MATCH is held for review.
- One year in the event name supplies season. Match events without a year use
  START_AT's year. Memberships without a clear year require an override.
  An ambiguous multi-year name also requires an override.
- Member product prefix comes from CONTROL, package from the event name without
  its year. Round is extracted only from explicit 'round N' or 'rd N' text.
  Opposition and offer code are not guessed. Opposition can be overridden;
  offer_code is omitted until a source mapping is confirmed.
- EVENT_OVERRIDES is empty initially and used only for exceptions.
- SUBSCRIPTION_GROUP_CONFIG is seeded once from existing Braze group IDs.
  Environment, target, minimum age and enabled status are editable there.
  These destination IDs cannot be discovered from Vivenu. No IDs occur in payload SQL.
- Environment selects subscription configuration only. This file's publication
  targets are explicitly production; changing ENVIRONMENT does not redirect them.

PROCESSING
- Only COMPLETE / RECEIVED AUD orders qualify initially. Other statuses are
  reported in V_ISSUES, including cancellations and unpaid reservations.
- Source prices are used as dollars, consistent with supplied examples.
  Totals sum eligible ticket lines, excluding separate fees, as in the old process.
- Whole orders with partial cancellation detail are held pending net-quantity
  verification. No refund or unsubscribe is inferred from disappearing records.
- Membership orders require matching VALID tickets with member number/barcode
  and complete ticket counts. Incomplete orders are visible in V_ISSUES.
- Existing complimentary/stakeholder membership exclusions are retained.
- Profile-only customers without a qualifying purchase do not become candidates.
- Full recomputation detects customer/ticket/config changes; MERGE updates only
  changed payloads. No source watermark can hide related-record changes.
- UTC TIMESTAMP_NTZ UPDATED_AT, not CURRENT_DATE or a future-dated value.
- Changed published events remain held unless ALLOW_EVENT_REPLAY is enabled;
  a resent event may duplicate activity in Braze. No cancellation retracts history.
- Atomic four-table publication; validation outputs preserve their own history.
  V_CANDIDATES shows the current eligible set. Publication uses that current set.

Run with source SELECT, build-schema CREATE and warehouse access. Publication
also requires DML rights on the existing targets and UTC TIMESTAMP_NTZ timestamp
columns. The SQL has local parser/sample checks only, not Snowflake execution.
Live validation must include linked member tickets and a normal match purchase.
*/

