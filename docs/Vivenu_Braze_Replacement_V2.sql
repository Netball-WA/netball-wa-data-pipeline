SELECT * FROM SUBSCRIPTION_GROUP_CONFIG ORDER BY ENVIRONMENT,TARGET_NAME,GROUP_ID;

-- Identity case differences can split one person into two legacy email hashes.
SELECT LOWER(PAYLOAD:email::VARCHAR) AS NORMALISED_EMAIL,
 COUNT(DISTINCT EXTERNAL_ID) AS IDENTIFIERS
FROM V_PROFILE_CANDIDATES GROUP BY NORMALISED_EMAIL
HAVING COUNT(DISTINCT EXTERNAL_ID)>1;

-- Missing DOB retains an empty age-gated group array. Review suspicious dates.
SELECT ORDER_ID,TICKET_ID,MEMBER_NUMBER,DOB,MEMBER_SINCE
FROM V_MEMBERS
WHERE DOB IS NULL OR MEMBER_SINCE=TO_CHAR(DOB,'YYYY-MM-DD');

-- Purchaser cannot always be assumed to be a ticket holder/member.
