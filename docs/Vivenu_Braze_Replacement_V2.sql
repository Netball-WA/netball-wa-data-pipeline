   for exceptions; adjust the membership name rule if needed. Review the seeded
   SUBSCRIPTION_GROUP_CONFIG settings. Run SP_REFRESH_VIVENU_BRAZE(FALSE) again.
B. Review source status coverage, V_ISSUES, member allocations and price totals.
   If production UPDATED_AT is DATE, review a migration to UTC TIMESTAMP_NTZ with your Braze sync before
   publishing. This script requires TIMESTAMP_NTZ and rejects DATE/TZ/LTZ.
C. Confirm Braze syncs use these four existing ingestion tables. Validate the
