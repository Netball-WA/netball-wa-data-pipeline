CREATE OR REPLACE PROCEDURE SP_REFRESH_VIVENU_BRAZE(PUBLISH BOOLEAN)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
 BAD NUMBER DEFAULT 0;
 CAN_PUBLISH BOOLEAN DEFAULT FALSE;
 REPLAY BOOLEAN DEFAULT FALSE;
 RUN_AT TIMESTAMP_NTZ;
 GUARD EXCEPTION (-20001,'Validation failed. Check mappings, keys, target types and CONTROL.');
BEGIN
 SELECT COUNT(*) INTO :BAD FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.CONTROL WHERE CONFIG_ID=1;
 IF (BAD<>1) THEN RAISE GUARD; END IF;
 SELECT ALLOW_PUBLISH,ALLOW_EVENT_REPLAY INTO :CAN_PUBLISH,:REPLAY
 FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.CONTROL WHERE CONFIG_ID=1;
 IF (PUBLISH AND NOT COALESCE(CAN_PUBLISH,FALSE)) THEN RAISE GUARD; END IF;
 SELECT COUNT(*) INTO :BAD FROM (
 SELECT EVENT_ID FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.EVENT_OVERRIDES GROUP BY EVENT_ID HAVING COUNT(*)>1);
 IF (BAD>0) THEN RAISE GUARD; END IF;
 SELECT COUNT(*) INTO :BAD FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.EVENT_OVERRIDES
 WHERE SALE_KIND IS NOT NULL AND SALE_KIND NOT IN ('MATCH','MEMBER');
 IF (BAD>0) THEN RAISE GUARD; END IF;

 SELECT COUNT(*) INTO :BAD FROM (
 SELECT ENVIRONMENT,TARGET_NAME,GROUP_ID FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.SUBSCRIPTION_GROUP_CONFIG
 GROUP BY ENVIRONMENT,TARGET_NAME,GROUP_ID HAVING COUNT(*)>1);
 IF (BAD>0) THEN RAISE GUARD; END IF;
 SELECT COUNT(*) INTO :BAD FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.SUBSCRIPTION_GROUP_CONFIG
 WHERE ENABLED AND (GROUP_ID IS NULL OR TRIM(GROUP_ID)='' OR MIN_AGE<0
 OR ENVIRONMENT IS NULL OR TARGET_NAME NOT IN
 ('TICKETEK_NWA_PROFILES','TICKETEK_MEMBER_PROFILES','TICKETEK_NWA_SALES','TICKETEK_MEMBER_SALES'));
 IF (BAD>0) THEN RAISE GUARD; END IF;
 SELECT COUNT(*) INTO :BAD FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.CONTROL WHERE CONFIG_ID=1 AND
 (DEFAULT_SALE_KIND IS DISTINCT FROM 'MATCH' OR MEMBER_EVENT_NAME_REGEX IS NULL
 OR ENVIRONMENT IS NULL OR MEMBER_PRODUCT_PREFIX IS NULL);
 IF (BAD>0) THEN RAISE GUARD; END IF;

 -- DDL before transaction. Snapshot candidates for consistent output updates.
 CREATE OR REPLACE TEMPORARY TABLE BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.RUN_CANDIDATES AS
 SELECT TARGET_NAME,EXTERNAL_ID,PARSE_JSON(TO_JSON(PAYLOAD)) AS PAYLOAD,
 COALESCE(PAYLOAD:properties.order_id::VARCHAR,'') AS ORDER_KEY
 FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.V_CANDIDATES;
 SELECT COUNT(*) INTO :BAD FROM (
 SELECT TARGET_NAME,EXTERNAL_ID,ORDER_KEY FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.RUN_CANDIDATES
 GROUP BY TARGET_NAME,EXTERNAL_ID,ORDER_KEY HAVING COUNT(*)>1);
 IF (BAD>0) THEN RAISE GUARD; END IF;

 IF (PUBLISH) THEN
  -- Require existing three-column contracts, including UTC TIMESTAMP_NTZ update precision.
  SELECT COUNT(*) INTO :BAD
  FROM BRAZE_CLOUD_PRODUCTION.INFORMATION_SCHEMA.COLUMNS
  WHERE TABLE_SCHEMA='INGESTION'
   AND TABLE_NAME IN ('TICKETEK_NWA_PROFILES','TICKETEK_NWA_SALES',
                     'TICKETEK_MEMBER_PROFILES','TICKETEK_MEMBER_SALES')
   AND ((COLUMN_NAME='UPDATED_AT' AND DATA_TYPE='TIMESTAMP_NTZ')
    OR (COLUMN_NAME='EXTERNAL_ID' AND DATA_TYPE IN ('TEXT','VARCHAR'))
    OR (COLUMN_NAME='PAYLOAD' AND DATA_TYPE IN ('TEXT','VARCHAR')));
  IF (BAD<>12) THEN RAISE GUARD; END IF;
  SELECT COUNT(*) INTO :BAD FROM (
   SELECT EXTERNAL_ID FROM BRAZE_CLOUD_PRODUCTION.INGESTION.TICKETEK_NWA_PROFILES
   GROUP BY EXTERNAL_ID HAVING COUNT(*)>1);
  IF (BAD>0) THEN RAISE GUARD; END IF;
  SELECT COUNT(*) INTO :BAD FROM (
   SELECT EXTERNAL_ID,TRY_PARSE_JSON(PAYLOAD):properties.order_id::VARCHAR FROM BRAZE_CLOUD_PRODUCTION.INGESTION.TICKETEK_NWA_SALES
   GROUP BY EXTERNAL_ID,TRY_PARSE_JSON(PAYLOAD):properties.order_id::VARCHAR HAVING COUNT(*)>1);
  IF (BAD>0) THEN RAISE GUARD; END IF;
  SELECT COUNT(*) INTO :BAD FROM (
   SELECT EXTERNAL_ID FROM BRAZE_CLOUD_PRODUCTION.INGESTION.TICKETEK_MEMBER_PROFILES
   GROUP BY EXTERNAL_ID HAVING COUNT(*)>1);
  IF (BAD>0) THEN RAISE GUARD; END IF;
  SELECT COUNT(*) INTO :BAD FROM (
   SELECT EXTERNAL_ID,TRY_PARSE_JSON(PAYLOAD):properties.order_id::VARCHAR FROM BRAZE_CLOUD_PRODUCTION.INGESTION.TICKETEK_MEMBER_SALES
   GROUP BY EXTERNAL_ID,TRY_PARSE_JSON(PAYLOAD):properties.order_id::VARCHAR HAVING COUNT(*)>1);
  IF (BAD>0) THEN RAISE GUARD; END IF;
 END IF;
 RUN_AT := CONVERT_TIMEZONE('UTC',CURRENT_TIMESTAMP())::TIMESTAMP_NTZ;
 BEGIN
  BEGIN TRANSACTION;
  MERGE INTO BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.TICKETEK_NWA_PROFILES t USING
   (SELECT * FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.RUN_CANDIDATES WHERE TARGET_NAME='TICKETEK_NWA_PROFILES') s
  ON t.EXTERNAL_ID=s.EXTERNAL_ID
  WHEN MATCHED AND TRY_PARSE_JSON(t.PAYLOAD) IS DISTINCT FROM s.PAYLOAD
   THEN UPDATE SET UPDATED_AT=:RUN_AT,PAYLOAD=TO_JSON(s.PAYLOAD)
  WHEN NOT MATCHED THEN INSERT(UPDATED_AT,EXTERNAL_ID,PAYLOAD)
   VALUES(:RUN_AT,s.EXTERNAL_ID,TO_JSON(s.PAYLOAD));
  MERGE INTO BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.TICKETEK_NWA_SALES t USING
   (SELECT * FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.RUN_CANDIDATES WHERE TARGET_NAME='TICKETEK_NWA_SALES') s
  ON t.EXTERNAL_ID=s.EXTERNAL_ID AND TRY_PARSE_JSON(t.PAYLOAD):properties.order_id::VARCHAR=s.ORDER_KEY
  WHEN MATCHED AND TRY_PARSE_JSON(t.PAYLOAD) IS DISTINCT FROM s.PAYLOAD
   THEN UPDATE SET UPDATED_AT=:RUN_AT,PAYLOAD=TO_JSON(s.PAYLOAD)
  WHEN NOT MATCHED THEN INSERT(UPDATED_AT,EXTERNAL_ID,PAYLOAD)
   VALUES(:RUN_AT,s.EXTERNAL_ID,TO_JSON(s.PAYLOAD));
  MERGE INTO BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.TICKETEK_MEMBER_PROFILES t USING
   (SELECT * FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.RUN_CANDIDATES WHERE TARGET_NAME='TICKETEK_MEMBER_PROFILES') s
  ON t.EXTERNAL_ID=s.EXTERNAL_ID
  WHEN MATCHED AND TRY_PARSE_JSON(t.PAYLOAD) IS DISTINCT FROM s.PAYLOAD
   THEN UPDATE SET UPDATED_AT=:RUN_AT,PAYLOAD=TO_JSON(s.PAYLOAD)
  WHEN NOT MATCHED THEN INSERT(UPDATED_AT,EXTERNAL_ID,PAYLOAD)
   VALUES(:RUN_AT,s.EXTERNAL_ID,TO_JSON(s.PAYLOAD));
  MERGE INTO BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.TICKETEK_MEMBER_SALES t USING
   (SELECT * FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.RUN_CANDIDATES WHERE TARGET_NAME='TICKETEK_MEMBER_SALES') s
  ON t.EXTERNAL_ID=s.EXTERNAL_ID AND TRY_PARSE_JSON(t.PAYLOAD):properties.order_id::VARCHAR=s.ORDER_KEY
  WHEN MATCHED AND TRY_PARSE_JSON(t.PAYLOAD) IS DISTINCT FROM s.PAYLOAD
   THEN UPDATE SET UPDATED_AT=:RUN_AT,PAYLOAD=TO_JSON(s.PAYLOAD)
  WHEN NOT MATCHED THEN INSERT(UPDATED_AT,EXTERNAL_ID,PAYLOAD)
   VALUES(:RUN_AT,s.EXTERNAL_ID,TO_JSON(s.PAYLOAD));
  IF (PUBLISH) THEN
   MERGE INTO BRAZE_CLOUD_PRODUCTION.INGESTION.TICKETEK_NWA_PROFILES t USING
    (SELECT * FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.RUN_CANDIDATES WHERE TARGET_NAME='TICKETEK_NWA_PROFILES') s
   ON t.EXTERNAL_ID=s.EXTERNAL_ID
   WHEN MATCHED AND TRY_PARSE_JSON(t.PAYLOAD) IS DISTINCT FROM s.PAYLOAD
    THEN UPDATE SET UPDATED_AT=:RUN_AT,PAYLOAD=TO_JSON(s.PAYLOAD)
   WHEN NOT MATCHED THEN INSERT(UPDATED_AT,EXTERNAL_ID,PAYLOAD)
    VALUES(:RUN_AT,s.EXTERNAL_ID,TO_JSON(s.PAYLOAD));
   MERGE INTO BRAZE_CLOUD_PRODUCTION.INGESTION.TICKETEK_NWA_SALES t USING
    (SELECT * FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.RUN_CANDIDATES WHERE TARGET_NAME='TICKETEK_NWA_SALES') s
   ON t.EXTERNAL_ID=s.EXTERNAL_ID AND TRY_PARSE_JSON(t.PAYLOAD):properties.order_id::VARCHAR=s.ORDER_KEY
   WHEN MATCHED AND TRY_PARSE_JSON(t.PAYLOAD) IS DISTINCT FROM s.PAYLOAD AND :REPLAY
    THEN UPDATE SET UPDATED_AT=:RUN_AT,PAYLOAD=TO_JSON(s.PAYLOAD)
   WHEN NOT MATCHED THEN INSERT(UPDATED_AT,EXTERNAL_ID,PAYLOAD)
    VALUES(:RUN_AT,s.EXTERNAL_ID,TO_JSON(s.PAYLOAD));
   MERGE INTO BRAZE_CLOUD_PRODUCTION.INGESTION.TICKETEK_MEMBER_PROFILES t USING
    (SELECT * FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.RUN_CANDIDATES WHERE TARGET_NAME='TICKETEK_MEMBER_PROFILES') s
   ON t.EXTERNAL_ID=s.EXTERNAL_ID
   WHEN MATCHED AND TRY_PARSE_JSON(t.PAYLOAD) IS DISTINCT FROM s.PAYLOAD
    THEN UPDATE SET UPDATED_AT=:RUN_AT,PAYLOAD=TO_JSON(s.PAYLOAD)
   WHEN NOT MATCHED THEN INSERT(UPDATED_AT,EXTERNAL_ID,PAYLOAD)
    VALUES(:RUN_AT,s.EXTERNAL_ID,TO_JSON(s.PAYLOAD));
   MERGE INTO BRAZE_CLOUD_PRODUCTION.INGESTION.TICKETEK_MEMBER_SALES t USING
    (SELECT * FROM BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.RUN_CANDIDATES WHERE TARGET_NAME='TICKETEK_MEMBER_SALES') s
   ON t.EXTERNAL_ID=s.EXTERNAL_ID AND TRY_PARSE_JSON(t.PAYLOAD):properties.order_id::VARCHAR=s.ORDER_KEY
   WHEN MATCHED AND TRY_PARSE_JSON(t.PAYLOAD) IS DISTINCT FROM s.PAYLOAD AND :REPLAY
    THEN UPDATE SET UPDATED_AT=:RUN_AT,PAYLOAD=TO_JSON(s.PAYLOAD)
   WHEN NOT MATCHED THEN INSERT(UPDATED_AT,EXTERNAL_ID,PAYLOAD)
    VALUES(:RUN_AT,s.EXTERNAL_ID,TO_JSON(s.PAYLOAD));
  END IF;
  COMMIT;
 EXCEPTION WHEN OTHER THEN
  ROLLBACK;
  RAISE;
 END;
 RETURN IFF(PUBLISH,'Published eligible rows to existing Braze tables. Review V_ISSUES and event changes.',
 'Validation outputs refreshed. Existing Braze tables unchanged. Review V_ISSUES.');
END;
$$;

-- A single refresh replaces four parallel transformations so shared identities
-- and source mapping are consistent. No scheduled publication until enabled.
CREATE TASK IF NOT EXISTS VIVENU_BRAZE_REFRESH
 WAREHOUSE=WH_BRAZE_PRD
 SCHEDULE='USING CRON 0 6/8 * * * Australia/Perth'
 ALLOW_OVERLAPPING_EXECUTION=FALSE
AS CALL BRAZE_CLOUD_PRODUCTION.VIVENU_BRAZE_V2.SP_REFRESH_VIVENU_BRAZE(TRUE);

