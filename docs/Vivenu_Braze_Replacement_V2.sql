-- Automatic classification is a visible business rule, not an API guarantee:
-- membership-named events -> MEMBER; other named ticket events -> configured
-- default MATCH. A line with a plan or MULTI ticket under a default-match event
-- is held for classification review, rather than silently sent as a match sale.
-- Change CONTROL.MEMBER_EVENT_NAME_REGEX or add an override for exceptions.
CREATE OR REPLACE VIEW V_EVENT_MAP AS
WITH inferred AS (
 SELECT e.*,
 CASE WHEN NULLIF(TRIM(e.EVENT_NAME),'') IS NULL THEN NULL
  WHEN REGEXP_LIKE(e.EVENT_NAME,c.MEMBER_EVENT_NAME_REGEX,'i') THEN 'MEMBER'
  ELSE c.DEFAULT_SALE_KIND END AS INFERRED_KIND,
 CASE WHEN REGEXP_COUNT(e.EVENT_NAME,'(19|20)[0-9]{2}')=1
  THEN REGEXP_SUBSTR(e.EVENT_NAME,'(19|20)[0-9]{2}') END AS NAME_SEASON,
 c.MEMBER_PRODUCT_PREFIX,
 CASE WHEN NULLIF(TRIM(e.EVENT_NAME),'') IS NULL THEN 'MISSING_NAME'
  WHEN REGEXP_LIKE(e.EVENT_NAME,c.MEMBER_EVENT_NAME_REGEX,'i') THEN 'MEMBERSHIP_NAME_RULE'
  ELSE 'DEFAULT_MATCH_RULE' END AS INFERRED_REASON
 FROM RAW_INGESTION.VIVENU_NATIVE.EVENTS e
 CROSS JOIN CONTROL c WHERE c.CONFIG_ID=1
), resolved AS (
 SELECT e.EVENT_ID,e.SELLER_ID,e.EVENT_NAME,e.START_AT AS EVENT_AT,
 COALESCE(o.SALE_KIND,e.INFERRED_KIND) AS SALE_KIND,
 COALESCE(o.SEASON,e.NAME_SEASON,
  IFF(COALESCE(o.SALE_KIND,e.INFERRED_KIND)='MATCH'
   AND REGEXP_COUNT(e.EVENT_NAME,'(19|20)[0-9]{2}')=0,
   TO_CHAR(e.START_AT,'YYYY'),NULL)) AS SEASON,
 o.PRODUCT_NAME AS OVERRIDE_PRODUCT_NAME,o.PACKAGE_NAME AS OVERRIDE_PACKAGE_NAME,
 e.MEMBER_PRODUCT_PREFIX,o.OPPOSITION,
 COALESCE(o.ROUND_NAME,REGEXP_SUBSTR(e.EVENT_NAME,
  '(round|rd)[[:space:]]*([0-9]+)',1,1,'ie',2)) AS ROUND_NAME,
 COALESCE(o.ENABLED,TRUE) AS ENABLED,
 IFF(o.SALE_KIND IS NOT NULL,'OVERRIDE',e.INFERRED_REASON) AS CLASSIFICATION_REASON
 FROM inferred e LEFT JOIN EVENT_OVERRIDES o ON o.EVENT_ID=e.EVENT_ID
)
SELECT EVENT_ID,SELLER_ID,EVENT_NAME,EVENT_AT,SALE_KIND,SEASON,
 COALESCE(OVERRIDE_PRODUCT_NAME,
  IFF(SALE_KIND='MEMBER',MEMBER_PRODUCT_PREFIX||SEASON,EVENT_NAME)) AS PRODUCT_NAME,
 COALESCE(OVERRIDE_PACKAGE_NAME,
  IFF(SALE_KIND='MEMBER',TRIM(REGEXP_REPLACE(EVENT_NAME,'(19|20)[0-9]{2}','')),NULL)) AS PACKAGE_NAME,
 OPPOSITION,ROUND_NAME,ENABLED,CLASSIFICATION_REASON
FROM resolved;

CREATE OR REPLACE FUNCTION CLEAN_PHONE(P VARCHAR)
RETURNS VARCHAR LANGUAGE SQL AS $$
CASE
 WHEN NULLIF(REGEXP_REPLACE(P,'[^0-9+]',''),'') IS NULL THEN NULL
 WHEN REGEXP_REPLACE(P,'[^0-9+]','') LIKE '+%' THEN REGEXP_REPLACE(P,'[^0-9+]','')
 WHEN REGEXP_REPLACE(P,'[^0-9]','') LIKE '610%'
  THEN '+61'||SUBSTR(REGEXP_REPLACE(P,'[^0-9]',''),4)
 WHEN REGEXP_REPLACE(P,'[^0-9]','') LIKE '0%'
  THEN '+61'||SUBSTR(REGEXP_REPLACE(P,'[^0-9]',''),2)
 ELSE '+'||REGEXP_REPLACE(P,'[^0-9]','') END
$$;

-- 2. Use only the updated source views. Do not read the raw table.
CREATE OR REPLACE VIEW V_CUSTOMERS AS
SELECT CUSTOMER_ID,SELLER_ID,NULLIF(TRIM(EMAIL),'') AS EMAIL,
 NULLIF(TRIM(FIRST_NAME),'') AS FIRST_NAME,NULLIF(TRIM(LAST_NAME),'') AS LAST_NAME,
 PHONE,LOCATION_CITY AS CITY,DOB,GENDER,LEGACY_TICKETEK_CUSTOMER_ID AS LEGACY_CUSTOMER_ID,
 LAST_CHANGED_AT
FROM RAW_INGESTION.VIVENU_NATIVE.CUSTOMERS;

-- Recover one header per transaction; TRANSACTIONS already expands its lines.
CREATE OR REPLACE VIEW V_ORDER_HEADERS AS
SELECT * FROM RAW_INGESTION.VIVENU_NATIVE.TRANSACTIONS
QUALIFY ROW_NUMBER() OVER(PARTITION BY TRANSACTION_ID
 ORDER BY LINE_ITEM_INDEX ASC NULLS LAST)=1;

CREATE OR REPLACE VIEW V_ORDERS AS
SELECT r.TRANSACTION_ID AS ORDER_ID,r.SELLER_ID,r.EVENT_ID,r.CUSTOMER_ID,
 COALESCE(NULLIF(TRIM(r.EMAIL),''),c.EMAIL) AS EMAIL,
 COALESCE(NULLIF(TRIM(r.FIRST_NAME),''),c.FIRST_NAME) AS FIRST_NAME,
 COALESCE(NULLIF(TRIM(r.LAST_NAME),''),c.LAST_NAME) AS LAST_NAME,
 COALESCE(NULLIF(r.PHONE,''),c.PHONE) AS PHONE,
 COALESCE(NULLIF(r.LOCATION_CITY,''),c.CITY) AS CITY,
 UPPER(r.STATUS) AS STATUS,UPPER(r.PAYMENT_STATUS) AS PAYMENT_STATUS,
 r.CURRENCY,r.REAL_PRICE AS ORDER_TOTAL,r.CREATED_AT,
 r.CANCELLATION_ITEM_COUNT AS CANCEL_ITEM_COUNT,r.LINE_ITEMS AS LINES,r.LAST_CHANGED_AT,
 m.SALE_KIND,m.SEASON,m.PRODUCT_NAME,m.PACKAGE_NAME,m.OPPOSITION,m.ROUND_NAME,
 m.EVENT_NAME,m.EVENT_AT,m.CLASSIFICATION_REASON,m.ENABLED AS EVENT_ENABLED
FROM V_ORDER_HEADERS r
LEFT JOIN V_CUSTOMERS c ON c.CUSTOMER_ID=r.CUSTOMER_ID AND c.SELLER_ID=r.SELLER_ID
LEFT JOIN V_EVENT_MAP m ON m.EVENT_ID=r.EVENT_ID AND m.SELLER_ID=r.SELLER_ID;

CREATE OR REPLACE VIEW V_EVENT_CATEGORIES AS
SELECT e.EVENT_ID,e.SELLER_ID,
 c.VALUE:ref::VARCHAR AS CATEGORY_REF,c.VALUE:name::VARCHAR AS CATEGORY_NAME
FROM RAW_INGESTION.VIVENU_NATIVE.EVENTS e,
 LATERAL FLATTEN(INPUT=>e.CATEGORIES) c
QUALIFY ROW_NUMBER() OVER(PARTITION BY e.EVENT_ID,c.VALUE:ref::VARCHAR
 ORDER BY c.INDEX)=1;

CREATE OR REPLACE VIEW V_LINES AS
SELECT o.*,t.LINE_ITEM_INDEX AS LINE_INDEX,t.LINE_ITEM_ID AS LINE_ID,
 t.LINE_ITEM_TICKET_TYPE_ID AS PRODUCT_ID,t.LINE_ITEM_NAME AS LINE_NAME,
 t.LINE_ITEM_PRICE AS UNIT_PRICE,
 TRY_TO_DECIMAL(t.LINE_ITEM_DATA:amount::VARCHAR,18,4) AS QUANTITY,
 t.LINE_ITEM_CATEGORY_REF AS CATEGORY_REF,t.LINE_ITEM_PLAN_ID AS PLAN_ID
FROM V_ORDERS o JOIN RAW_INGESTION.VIVENU_NATIVE.TRANSACTIONS t
 ON t.TRANSACTION_ID=o.ORDER_ID AND t.SELLER_ID=o.SELLER_ID
WHERE t.LINE_ITEM_INDEX IS NOT NULL;

CREATE OR REPLACE VIEW V_TICKETS AS
SELECT TICKET_ID,SELLER_ID,NULLIF(TRANSACTION_ID,'') AS ORDER_ID,
 CART_ITEM_ID AS LINE_ID,EVENT_ID,TICKET_TYPE_ID AS PRODUCT_ID,
 NULLIF(TRIM(EMAIL),'') AS EMAIL,NULLIF(TRIM(FIRST_NAME),'') AS FIRST_NAME,
 NULLIF(TRIM(LAST_NAME),'') AS LAST_NAME,LOCATION_CITY AS CITY,
 CATEGORY_NAME,TICKET_NAME AS TYPE_NAME,UPPER(STATUS) AS STATUS,
 BARCODE,DOB,GENDER,NULLIF(MEMBER_NUMBER,'') AS MEMBER_NUMBER,
 MEMBER_SINCE,LAST_CHANGED_AT,TICKET_TYPE
FROM RAW_INGESTION.VIVENU_NATIVE.TICKETS;

CREATE OR REPLACE VIEW V_CLASSIFICATION_REVIEW AS
WITH multi_events AS (
 SELECT DISTINCT ORDER_ID,SELLER_ID,EVENT_ID FROM V_TICKETS
 WHERE UPPER(TICKET_TYPE)='MULTI'
)
SELECT DISTINCT l.ORDER_ID FROM V_LINES l
LEFT JOIN multi_events m ON m.ORDER_ID=l.ORDER_ID AND m.SELLER_ID=l.SELLER_ID
 AND m.EVENT_ID=l.EVENT_ID
WHERE l.CLASSIFICATION_REASON='DEFAULT_MATCH_RULE'
 AND (NULLIF(l.PLAN_ID,'') IS NOT NULL OR m.ORDER_ID IS NOT NULL);

-- Order-wide checks prevent incomplete or misleading totals.
CREATE OR REPLACE VIEW V_ORDER_CHECKS AS
WITH checks AS (
 SELECT ORDER_ID,
 COUNT_IF(LINE_ID IS NULL OR UNIT_PRICE IS NULL OR UNIT_PRICE<0
  OR QUANTITY IS NULL OR QUANTITY<=0 OR QUANTITY<>FLOOR(QUANTITY) OR PRODUCT_ID IS NULL) AS BAD_LINES,
 COUNT(*)-COUNT(DISTINCT LINE_ID) AS DUPLICATE_LINES
 FROM V_LINES GROUP BY ORDER_ID
)
SELECT o.ORDER_ID,
 CASE
 WHEN o.SALE_KIND IS NULL THEN 'MISSING_EVENT_CLASSIFICATION'
 WHEN NOT o.EVENT_ENABLED THEN 'EVENT_DISABLED'
 WHEN o.SEASON IS NULL THEN 'SEASON_REVIEW'
 WHEN cr.ORDER_ID IS NOT NULL THEN 'MEMBERSHIP_CLASSIFICATION_REVIEW'
 WHEN o.SALE_KIND NOT IN ('MATCH','MEMBER') THEN 'INVALID_EVENT_KIND'
 WHEN o.STATUS IS DISTINCT FROM 'COMPLETE' THEN 'ORDER_NOT_COMPLETE'
 WHEN o.PAYMENT_STATUS IS DISTINCT FROM 'RECEIVED' THEN 'PAYMENT_NOT_RECEIVED'
 WHEN o.CANCEL_ITEM_COUNT>0 THEN 'PARTIAL_CANCELLATION_REVIEW'
 WHEN o.CURRENCY IS DISTINCT FROM 'AUD' THEN 'CURRENCY_REVIEW'
 WHEN o.EMAIL IS NULL THEN 'MISSING_PURCHASER_EMAIL'
 WHEN o.CREATED_AT IS NULL THEN 'MISSING_ORDER_DATE'
 WHEN COALESCE(ARRAY_SIZE(o.LINES),0)=0 THEN 'NO_TICKET_LINES'
 WHEN c.BAD_LINES>0 THEN 'INVALID_LINE'
 WHEN c.DUPLICATE_LINES>0 THEN 'DUPLICATE_LINE_ID'
 ELSE 'READY' END AS RESULT
FROM V_ORDERS o LEFT JOIN checks c ON c.ORDER_ID=o.ORDER_ID
LEFT JOIN V_CLASSIFICATION_REVIEW cr ON cr.ORDER_ID=o.ORDER_ID;

CREATE OR REPLACE VIEW V_MEMBER_LINE_CHECKS AS
SELECT l.ORDER_ID,l.LINE_ID,l.QUANTITY,
 COUNT(t.TICKET_ID) AS VALID_TICKET_COUNT,
 COUNT_IF(t.TICKET_ID IS NOT NULL AND
  (COALESCE(t.FIRST_NAME,l.FIRST_NAME) IS NULL OR
   COALESCE(t.LAST_NAME,l.LAST_NAME) IS NULL OR
   t.MEMBER_NUMBER IS NULL OR t.BARCODE IS NULL)) AS INCOMPLETE_MEMBERS
FROM V_LINES l JOIN V_ORDER_CHECKS q ON q.ORDER_ID=l.ORDER_ID AND q.RESULT='READY'
LEFT JOIN V_TICKETS t ON t.ORDER_ID=l.ORDER_ID AND t.LINE_ID=l.LINE_ID
 AND t.SELLER_ID=l.SELLER_ID AND t.EVENT_ID=l.EVENT_ID
 AND t.PRODUCT_ID=l.PRODUCT_ID AND t.STATUS='VALID'
WHERE l.SALE_KIND='MEMBER'
GROUP BY l.ORDER_ID,l.LINE_ID,l.QUANTITY;

CREATE OR REPLACE VIEW V_ISSUES AS
SELECT ORDER_ID,RESULT AS ISSUE FROM V_ORDER_CHECKS WHERE RESULT<>'READY'
UNION ALL
SELECT DISTINCT ORDER_ID,'MEMBER_TICKET_COUNT_OR_DETAILS'
FROM V_MEMBER_LINE_CHECKS
WHERE VALID_TICKET_COUNT<>QUANTITY OR INCOMPLETE_MEMBERS>0;

CREATE OR REPLACE VIEW V_READY_LINES AS
SELECT l.* FROM V_LINES l
WHERE NOT EXISTS (SELECT 1 FROM V_ISSUES i WHERE i.ORDER_ID=l.ORDER_ID);

CREATE OR REPLACE VIEW V_MEMBERS AS
SELECT l.*, t.TICKET_ID,t.BARCODE,t.MEMBER_NUMBER,t.MEMBER_SINCE,t.DOB,t.GENDER,
 COALESCE(t.EMAIL,l.EMAIL) AS MEMBER_EMAIL,
 COALESCE(t.FIRST_NAME,l.FIRST_NAME) AS MEMBER_FIRST_NAME,
 COALESCE(t.LAST_NAME,l.LAST_NAME) AS MEMBER_LAST_NAME,
 COALESCE(t.CITY,l.CITY) AS MEMBER_CITY,
 t.CATEGORY_NAME,COALESCE(t.TYPE_NAME,l.LINE_NAME) AS TYPE_NAME,
 t.LAST_CHANGED_AT AS TICKET_CHANGED_AT
FROM V_READY_LINES l JOIN V_TICKETS t
 ON t.ORDER_ID=l.ORDER_ID AND t.LINE_ID=l.LINE_ID AND t.SELLER_ID=l.SELLER_ID
 AND t.EVENT_ID=l.EVENT_ID AND t.PRODUCT_ID=l.PRODUCT_ID AND t.STATUS='VALID'
WHERE l.SALE_KIND='MEMBER'
 AND LOWER(COALESCE(t.TYPE_NAME,l.LINE_NAME,'')) NOT LIKE '%complimentary%'
 AND LOWER(COALESCE(t.TYPE_NAME,l.LINE_NAME,'')) NOT LIKE '%stakeholder%';

-- 3. Profile payloads. One deterministic profile per exact trimmed email.
-- Shared-email members: choose oldest known DOB, then newest purchase/ticket.
CREATE OR REPLACE VIEW V_PROFILE_PICKS AS
WITH p AS (
 SELECT 'TICKETEK_NWA_PROFILES' AS TARGET_NAME,EMAIL,FIRST_NAME,LAST_NAME,CITY,PHONE,
  NULL::DATE AS DOB,NULL::VARCHAR AS GENDER,NULL::VARCHAR AS MEMBER_NUMBER,
  NULL::VARCHAR AS MEMBER_SINCE,CREATED_AT,ORDER_ID,'' AS TICKET_ID
 FROM V_READY_LINES WHERE SALE_KIND='MATCH'
 UNION ALL
 SELECT 'TICKETEK_MEMBER_PROFILES',MEMBER_EMAIL,MEMBER_FIRST_NAME,MEMBER_LAST_NAME,
  MEMBER_CITY,PHONE,DOB,GENDER,MEMBER_NUMBER,MEMBER_SINCE,CREATED_AT,ORDER_ID,TICKET_ID
 FROM V_MEMBERS
)
SELECT * FROM p QUALIFY ROW_NUMBER() OVER (
 PARTITION BY TARGET_NAME,EMAIL
 ORDER BY DOB ASC NULLS LAST,CREATED_AT DESC,ORDER_ID DESC,TICKET_ID DESC)=1;

CREATE OR REPLACE VIEW V_PROFILE_SUBSCRIPTIONS AS
SELECT p.TARGET_NAME,p.EMAIL,
 ARRAY_AGG(OBJECT_CONSTRUCT('subscription_group_id',g.GROUP_ID,
  'subscription_state','subscribed')) WITHIN GROUP(ORDER BY g.GROUP_ID) AS GROUPS
FROM V_PROFILE_PICKS p CROSS JOIN CONTROL c
JOIN SUBSCRIPTION_GROUP_CONFIG g ON g.ENVIRONMENT=c.ENVIRONMENT
 AND g.TARGET_NAME=p.TARGET_NAME AND g.ENABLED
 AND (g.MIN_AGE IS NULL OR FLOOR(MONTHS_BETWEEN(CURRENT_DATE(),p.DOB)/12)>=g.MIN_AGE)
WHERE c.CONFIG_ID=1 GROUP BY p.TARGET_NAME,p.EMAIL;

CREATE OR REPLACE VIEW V_PROFILE_CANDIDATES AS
SELECT p.TARGET_NAME,SHA2(TRIM(p.EMAIL),256) AS EXTERNAL_ID,
 OBJECT_CONSTRUCT('country','AU',
 'email',IFF(p.TARGET_NAME='TICKETEK_NWA_PROFILES',LOWER(p.EMAIL),p.EMAIL),
 'first_name',IFF(p.TARGET_NAME='TICKETEK_NWA_PROFILES',INITCAP(p.FIRST_NAME),p.FIRST_NAME),
 'last_name',IFF(p.TARGET_NAME='TICKETEK_NWA_PROFILES',INITCAP(p.LAST_NAME),p.LAST_NAME),
 'home_city',IFF(p.TARGET_NAME='TICKETEK_NWA_PROFILES',INITCAP(p.CITY),p.CITY),
 'phone',CLEAN_PHONE(p.PHONE),'email_subscribe','subscribed',
 'Dob',p.DOB,'Gender',p.GENDER,'member_number',p.MEMBER_NUMBER,'member_since',p.MEMBER_SINCE,
 'subscription_groups',COALESCE(sg.GROUPS,ARRAY_CONSTRUCT())) AS PAYLOAD
FROM V_PROFILE_PICKS p LEFT JOIN V_PROFILE_SUBSCRIPTIONS sg
 ON sg.TARGET_NAME=p.TARGET_NAME AND sg.EMAIL=p.EMAIL;

-- Membership amounts allocated per member ticket, not repeated order totals.
CREATE OR REPLACE VIEW V_MEMBER_PRODUCTS AS
SELECT ORDER_ID,MEMBER_EMAIL AS EMAIL,CREATED_AT,PRODUCT_ID,UNIT_PRICE,
 SEASON,PACKAGE_NAME,CATEGORY_NAME,TYPE_NAME,PRODUCT_NAME,
 COUNT(*) AS QUANTITY,
 ARRAY_AGG(DISTINCT BARCODE) WITHIN GROUP(ORDER BY BARCODE) AS BARCODES
FROM V_MEMBERS
GROUP BY ORDER_ID,MEMBER_EMAIL,CREATED_AT,PRODUCT_ID,UNIT_PRICE,
 SEASON,PACKAGE_NAME,CATEGORY_NAME,TYPE_NAME,PRODUCT_NAME;

CREATE OR REPLACE VIEW V_EVENT_BASE AS
WITH match_products AS (
 SELECT ORDER_ID,EMAIL,FIRST_NAME,LAST_NAME,CREATED_AT,LINE_ID,
 UNIT_PRICE*QUANTITY AS LINE_TOTAL,
 OBJECT_CONSTRUCT('product_id',PRODUCT_ID,'product_name',COALESCE(PRODUCT_NAME,EVENT_NAME),
 'variant_id',CONCAT_WS('-',SEASON,'R'||COALESCE(ROUND_NAME,''),
 COALESCE(ec.CATEGORY_NAME,''),COALESCE(LINE_NAME,'')),
 'quantity',QUANTITY,'price',UNIT_PRICE,
 'metadata',OBJECT_CONSTRUCT('season',SEASON,'opposition',OPPOSITION,'round',ROUND_NAME,
 'price_category',ec.CATEGORY_NAME,'price_type',LINE_NAME,
 'purchase_date',TO_CHAR(CREATED_AT,'YYYY-MM-DD"T"HH24:MI:SSTZH:TZM'),
 'event_date',TO_CHAR(EVENT_AT,'YYYY-MM-DD"T"HH24:MI:SSTZH:TZM'))) AS PRODUCT
 FROM V_READY_LINES l LEFT JOIN V_EVENT_CATEGORIES ec
 ON ec.EVENT_ID=l.EVENT_ID AND ec.SELLER_ID=l.SELLER_ID
 AND ec.CATEGORY_REF=l.CATEGORY_REF
 WHERE SALE_KIND='MATCH'
), member_identity AS (
 SELECT ORDER_ID,MEMBER_EMAIL AS EMAIL,MEMBER_FIRST_NAME AS FIRST_NAME,
 MEMBER_LAST_NAME AS LAST_NAME,DOB FROM V_MEMBERS
 QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID,MEMBER_EMAIL
 ORDER BY DOB ASC NULLS LAST,TICKET_ID)=1
), member_products AS (
 SELECT p.ORDER_ID,p.EMAIL,i.FIRST_NAME,i.LAST_NAME,i.DOB,p.CREATED_AT,
 p.PRODUCT_ID,p.TYPE_NAME,p.CATEGORY_NAME,p.UNIT_PRICE,
 p.UNIT_PRICE*p.QUANTITY AS LINE_TOTAL,
 OBJECT_CONSTRUCT('product_id',p.PRODUCT_ID,'product_name',p.PRODUCT_NAME,
 'variant_id',CONCAT_WS('-',p.SEASON,COALESCE(p.PACKAGE_NAME,''),
 COALESCE(p.CATEGORY_NAME,''),COALESCE(p.TYPE_NAME,'')),
 'quantity',p.QUANTITY,'price',p.UNIT_PRICE,
 'metadata',OBJECT_CONSTRUCT('season',p.SEASON,'member_package',p.PACKAGE_NAME,
 'member_category',p.CATEGORY_NAME,'member_type',p.TYPE_NAME,
 'purchase_date',TO_CHAR(p.CREATED_AT,'YYYY-MM-DD"T"HH24:MI:SSTZH:TZM'),
 'member_barcode',p.BARCODES)) AS PRODUCT
 FROM V_MEMBER_PRODUCTS p JOIN member_identity i
 ON i.ORDER_ID=p.ORDER_ID AND i.EMAIL=p.EMAIL
), orders AS (
 SELECT 'TICKETEK_NWA_SALES' AS TARGET_NAME,'ecommerce.order_placed' AS EVENT_NAME,
 ORDER_ID,EMAIL,FIRST_NAME,LAST_NAME,CREATED_AT,NULL::DATE AS DOB,
 SUM(LINE_TOTAL)::NUMBER(18,2) AS TOTAL_VALUE,
 ARRAY_AGG(PRODUCT) WITHIN GROUP(ORDER BY LINE_ID) AS PRODUCTS
 FROM match_products GROUP BY ORDER_ID,EMAIL,FIRST_NAME,LAST_NAME,CREATED_AT
 UNION ALL
 SELECT 'TICKETEK_MEMBER_SALES','membership.completed',
 ORDER_ID,EMAIL,FIRST_NAME,LAST_NAME,CREATED_AT,DOB,
 SUM(LINE_TOTAL)::NUMBER(18,2),
 ARRAY_AGG(PRODUCT) WITHIN GROUP(ORDER BY PRODUCT_ID,TYPE_NAME,CATEGORY_NAME,UNIT_PRICE)
 FROM member_products GROUP BY ORDER_ID,EMAIL,FIRST_NAME,LAST_NAME,CREATED_AT,DOB
)
SELECT TARGET_NAME,ORDER_ID,EMAIL,DOB,SHA2(TRIM(EMAIL),256) AS EXTERNAL_ID,
 OBJECT_CONSTRUCT('country','AU','email',EMAIL,'first_name',FIRST_NAME,
 'last_name',LAST_NAME,'name',EVENT_NAME,
 'time',TO_CHAR(CREATED_AT,'YYYY-MM-DD"T"HH24:MI:SSTZH:TZM'),
 'properties',OBJECT_CONSTRUCT('order_id','vivenu:'||ORDER_ID,
 'total_value',TOTAL_VALUE,'currency','AUD','source','ticketing_platform','products',PRODUCTS)
 ) AS BASE_PAYLOAD
FROM orders;

CREATE OR REPLACE VIEW V_EVENT_SUBSCRIPTIONS AS
SELECT e.TARGET_NAME,e.ORDER_ID,e.EXTERNAL_ID,
 ARRAY_AGG(OBJECT_CONSTRUCT('subscription_group_id',g.GROUP_ID,
 'subscription_state','subscribed')) WITHIN GROUP(ORDER BY g.GROUP_ID) AS GROUPS
FROM V_EVENT_BASE e CROSS JOIN CONTROL c
JOIN SUBSCRIPTION_GROUP_CONFIG g ON g.ENVIRONMENT=c.ENVIRONMENT
 AND g.TARGET_NAME=e.TARGET_NAME AND g.ENABLED
 AND (g.MIN_AGE IS NULL OR FLOOR(MONTHS_BETWEEN(CURRENT_DATE(),e.DOB)/12)>=g.MIN_AGE)
WHERE c.CONFIG_ID=1 GROUP BY e.TARGET_NAME,e.ORDER_ID,e.EXTERNAL_ID;

CREATE OR REPLACE VIEW V_EVENT_CANDIDATES AS
SELECT e.TARGET_NAME,e.EXTERNAL_ID,
 IFF(e.TARGET_NAME='TICKETEK_MEMBER_SALES' OR sg.GROUPS IS NOT NULL,
 OBJECT_INSERT(e.BASE_PAYLOAD,'subscription_groups',COALESCE(sg.GROUPS,ARRAY_CONSTRUCT())),
 e.BASE_PAYLOAD) AS PAYLOAD
FROM V_EVENT_BASE e LEFT JOIN V_EVENT_SUBSCRIPTIONS sg
 ON sg.TARGET_NAME=e.TARGET_NAME AND sg.ORDER_ID=e.ORDER_ID AND sg.EXTERNAL_ID=e.EXTERNAL_ID;

CREATE OR REPLACE VIEW V_CANDIDATES AS
SELECT * FROM V_PROFILE_CANDIDATES UNION ALL SELECT * FROM V_EVENT_CANDIDATES;

