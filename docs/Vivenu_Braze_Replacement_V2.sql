 ON p.PAYLOAD:properties.order_id::VARCHAR='vivenu:'||i.ORDER_ID;

-- 5. Run the isolated build.
CALL SP_REFRESH_VIVENU_BRAZE(FALSE);

-- 6. Review results before cutover.
SELECT ISSUE,COUNT(*) AS ORDERS FROM V_ISSUES GROUP BY ISSUE ORDER BY ISSUE;
SELECT * FROM V_EVENT_CHANGES_HELD;
SELECT * FROM V_PUBLISHED_ORDER_ISSUES;
SELECT TARGET_NAME,COUNT(*) AS CANDIDATES FROM V_CANDIDATES GROUP BY TARGET_NAME;

-- Inspect automatically derived classifications and season/name choices.
SELECT EVENT_ID,EVENT_NAME,SALE_KIND,SEASON,PRODUCT_NAME,PACKAGE_NAME,
 CLASSIFICATION_REASON,OPPOSITION,ROUND_NAME,ENABLED
FROM V_EVENT_MAP ORDER BY SALE_KIND,EVENT_NAME;

