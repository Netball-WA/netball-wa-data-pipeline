D. Stop old refreshes, wait for any current graph run to finish, then publish.
   Preserve a backup and capture Braze sync watermarks before the first publish.

ALTER TASK BRAZE_CLOUD_PRODUCTION.INGESTION.TICKETEK_DATA_LOAD_START SUSPEND;
