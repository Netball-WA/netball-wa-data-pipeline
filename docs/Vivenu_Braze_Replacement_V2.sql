 SUM(UNIT_PRICE*QUANTITY) AS TICKET_LINE_TOTAL
FROM V_READY_LINES GROUP BY ORDER_ID
HAVING ABS(MAX(ORDER_TOTAL)-SUM(UNIT_PRICE*QUANTITY))>0.01;

/*
